/**
 * Generates supabase/seed/products.sql from lib/products.ts (the canonical catalog).
 *
 *   node scripts/generate-product-seed.mjs
 *
 * Requires Node 22.18+ (built-in TypeScript type stripping).
 * Re-run after editing the catalog, then apply the SQL to your database.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PRODUCTS } from "../lib/products.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;

const rows = PRODUCTS.map(
  (p) =>
    `  (${q(p.id)}, ${q(p.name)}, ${p.price}, ${p.originalPrice}, ${p.rating}, ${p.reviews}, ` +
    `${q(p.icon)}, ${q(p.category)}, ${q(p.badge)}, ${q(p.description)}, ${arr(p.tags)})`
);

const sql = `-- Generated by scripts/generate-product-seed.mjs from lib/products.ts. Do not edit by hand.
insert into public.products
  (id, name, price, original_price, rating, reviews, icon, category, badge, description, tags)
values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  price = excluded.price,
  original_price = excluded.original_price,
  rating = excluded.rating,
  reviews = excluded.reviews,
  icon = excluded.icon,
  category = excluded.category,
  badge = excluded.badge,
  description = excluded.description,
  tags = excluded.tags;
`;

const out = join(root, "supabase", "seed", "products.sql");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(`Wrote ${PRODUCTS.length} products to ${out}`);
